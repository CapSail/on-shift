let deck: string[] = [];

/** The next line from a shuffled deck, so you see all of them before any repeats. */
export function nextShiftyLine(): string {
  if (!deck.length) {
    deck = SHIFTY_LINES.slice();
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
  }
  return deck.pop()!;
}
